// Packs the skill icons into one SVG sprite (public/skills-sprite.svg) and writes
// app/assets/skills/sprite-version.js with a content hash for cache busting.
// Run with `npm run sprite` after adding or changing an icon in icons.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { icons } from '../app/assets/skills/icons.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skillsDir = path.join(root, 'app/assets/skills');

const toSymbol = (id, file) => {
  const src = readFileSync(path.join(skillsDir, file), 'utf8')
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!DOCTYPE[^>]*>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    // Strip editor metadata (Inkscape etc.): its namespaces are declared on the dropped root.
    .replace(/<metadata[\s\S]*?<\/metadata>/g, '')
    .replace(/<sodipodi:[^>]*\/>/g, '')
    .replace(/\s(?:inkscape|sodipodi):[\w-]+="[^"]*"/g, '')
    .trim();
  const open = src.match(/<svg\b([^>]*)>/);
  if (!open) throw new Error(`${file}: no <svg> root`);
  const viewBox = open[1].match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${file}: missing viewBox`);
  let inner = src.slice(open.index + open[0].length, src.lastIndexOf('</svg>'));
  // Gradients and clip paths share ids across files, so namespace them per icon.
  const ids = [...inner.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  for (const old of new Set(ids)) {
    const next = `${id}-${old}`;
    inner = inner
      .replaceAll(`id="${old}"`, `id="${next}"`)
      .replaceAll(`url(#${old})`, `url(#${next})`)
      .replaceAll(`href="#${old}"`, `href="#${next}"`);
  }
  return `<symbol id="${id}" viewBox="${viewBox}">${inner.trim()}</symbol>`;
};

const sprite =
  '<svg xmlns="http://www.w3.org/2000/svg">' +
  Object.entries(icons).map(([id, file]) => toSymbol(id, file)).join('') +
  '</svg>\n';

const hash = createHash('sha1').update(sprite).digest('hex').slice(0, 8);
writeFileSync(path.join(root, 'public/skills-sprite.svg'), sprite);
writeFileSync(
  path.join(skillsDir, 'sprite-version.js'),
  `// Generated by scripts/build-sprite.mjs. Do not edit.\nexport const SPRITE_URL = '/skills-sprite.svg?v=${hash}';\n`
);
console.log(`${Object.keys(icons).length} icons, ${(sprite.length / 1024).toFixed(1)} KB, v=${hash}`);
